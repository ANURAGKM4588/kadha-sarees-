-- 1. ERASE ALL OLD TABLES & DATA
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS bookings CASCADE;
DROP TABLE IF EXISTS newsletter_subscribers CASCADE;
DROP TABLE IF EXISTS products CASCADE;

-- 2. CREATE FRESH 'products' TABLE
CREATE TABLE products (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  fabric TEXT NOT NULL,
  category TEXT NOT NULL,
  color TEXT NOT NULL,
  description TEXT,
  price NUMERIC NOT NULL,
  was NUMERIC,
  discount NUMERIC DEFAULT 0,
  badge TEXT DEFAULT 'Handloom',
  img TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. CREATE FRESH 'orders' TABLE
CREATE TABLE orders (
  id TEXT PRIMARY KEY,
  customer_name TEXT NOT NULL,
  customer_email TEXT NOT NULL,
  initials TEXT,
  product_name TEXT NOT NULL,
  img TEXT NOT NULL,
  date TEXT NOT NULL,
  amount NUMERIC NOT NULL,
  status TEXT DEFAULT 'Processing',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. CREATE FRESH 'bookings' TABLE (Drape Consultations)
CREATE TABLE bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  interest TEXT NOT NULL,
  time_slot TEXT NOT NULL,
  status TEXT DEFAULT 'Pending',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. CREATE FRESH 'newsletter_subscribers' TABLE
CREATE TABLE newsletter_subscribers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  subscribed_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- ENABLE ROW LEVEL SECURITY (RLS) & SET PERMISSIVE POLICIES
-- ==============================================================================
ALTER TABLE products ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE bookings ENABLE ROW LEVEL SECURITY;
ALTER TABLE newsletter_subscribers ENABLE ROW LEVEL SECURITY;

-- Products: Everyone can read and manage
CREATE POLICY "Public can view products" ON products FOR SELECT USING (true);
CREATE POLICY "Public can insert products" ON products FOR INSERT WITH CHECK (true);
CREATE POLICY "Public can update products" ON products FOR UPDATE USING (true);
CREATE POLICY "Public can delete products" ON products FOR DELETE USING (true);

-- Orders: Everyone can read and create orders
CREATE POLICY "Public can view orders" ON orders FOR SELECT USING (true);
CREATE POLICY "Public can create orders" ON orders FOR INSERT WITH CHECK (true);
CREATE POLICY "Public can update orders" ON orders FOR UPDATE USING (true);
CREATE POLICY "Public can delete orders" ON orders FOR DELETE USING (true);

-- Bookings: Everyone can insert and read bookings
CREATE POLICY "Public can view bookings" ON bookings FOR SELECT USING (true);
CREATE POLICY "Public can create bookings" ON bookings FOR INSERT WITH CHECK (true);

-- Newsletter: Everyone can subscribe
CREATE POLICY "Public can view subscribers" ON newsletter_subscribers FOR SELECT USING (true);
CREATE POLICY "Public can subscribe" ON newsletter_subscribers FOR INSERT WITH CHECK (true);

